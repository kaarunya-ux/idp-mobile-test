"""Turns ``results/dl_results.json`` into the per-field tables of ``BASELINE.md`` (the committed baseline).

    python accuracy/dl/report.py [--out BASELINE.md]

Every card is invented, so the values it quotes are made up.
"""

import argparse
import json
import statistics
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from dl.card_set import FIELDS  # noqa: E402

HEADER = [
    "| {} | Fields | Correct | Exact | Wrong ACCEPTED | Wrong NEEDS_REVIEW | Missing | Review rate |",
    "|---|---|---|---|---|---|---|---|",
]


def _row(label: str, cells: list[dict]) -> str:
    if not cells:
        return f"| {label} | 0 | - | - | - | - | - | - |"
    count, outcomes = len(cells), Counter(c["outcome"] for c in cells)

    def share(n: int) -> str:
        return f"{100 * n / count:.0f}%"

    return (
        f"| {label} | {count} | {share(outcomes['correct'])} | {share(sum(bool(c['exact']) for c in cells))} "
        f"| **{outcomes['wrong_accepted']}** | {outcomes['wrong_review']} | {outcomes['missing']} | {share(sum(bool(c['reviewed']) for c in cells))} |"
    )


def field_table(rows: list[dict], fields: tuple[str, ...]) -> list[str]:
    return [HEADER[0].format("Field"), HEADER[1], *(_row(k, [r["fields"][k] for r in rows]) for k in fields)]


def by_defect(rows: list[dict]) -> list[str]:
    """Per picture defect: every field of every card that has it (a card with two defects counts under both)."""
    groups: dict[str, list[dict]] = {}
    for r in rows:
        for label in r["effects"] or ["clean"]:
            groups.setdefault(label, []).append(r)
    cells = {label: [c for r in group for c in r["fields"].values()] for label, group in groups.items()}
    return [HEADER[0].format("Defect"), HEADER[1], *(_row(f"{label} ({len(groups[label])} cards)", cells[label]) for label in sorted(cells))]


def accepted_wrong(rows: list[dict]) -> list[str]:
    """The fields that were wrong and ACCEPTED, with what was read and what was printed (all invented values)."""
    found = [(r, k, c) for r in rows for k, c in r["fields"].items() if c["outcome"] == "wrong_accepted"]
    lines = [f"{len(found)} fields, every one listed:", "", "| Card | Defects | Field | Read | Printed |", "|---|---|---|---|---|"]
    for r, key, cell in found:
        lines.append(f"| {r['card']} | {', '.join(r['effects']) or 'none'} | {key} | {cell['value']} | {r['truth'][key]} |")
    return lines


def by_layout(rows: list[dict]) -> list[str]:
    """Per way the card was sent (a driving licence goes as one side-by-side picture or as a front and a back picture)."""
    groups: dict[str, list[dict]] = {}
    for r in rows:
        groups.setdefault(r.get("layout", "single"), []).append(r)
    cells = {k: [c for r in g for c in r["fields"].values()] for k, g in groups.items()}
    return [HEADER[0].format("Layout"), HEADER[1], *(_row(f"{k} ({len(groups[k])} cards)", cells[k]) for k in sorted(cells))]


def build(rows: list[dict]) -> str:
    fields = FIELDS
    normal = [r for r in rows if r["group"] == "normal"]
    bad = [r for r in rows if r["group"] == "invalid_number"]
    seconds = [r["seconds"] for r in rows if r["seconds"]]
    everything = [c for r in normal for c in r["fields"].values()]
    out = [
        "# Driving licence accuracy baseline (extraction `POST /api/v1/extract`)",
        "",
        f"{len(rows)} invented cards, English only: {len(normal)} with a valid number (scored for accuracy, {len(everything)} fields) and "
        f"{len(bad)} whose number is of the wrong shape (own class, {len(bad) * len(fields)} fields, not in the figures below). "
        "Generated by `report.py` from `run.py`; the committed numbers are the baseline.",
        "",
        "How a field is scored: **Correct** the printed value, ignoring case, spacing and punctuation (dates in any format). "
        "**Exact** the value is the printed text character for character. **Wrong ACCEPTED** a different value marked ACCEPTED: nobody "
        "will check it, so this is the number that matters most. **Wrong NEEDS_REVIEW** a different value a person will see. "
        "**Missing** no value. **Review rate** the share of fields marked NEEDS_REVIEW, right or wrong.",
        "",
        "## All valid-number cards",
        "",
        HEADER[0].format("All"),
        HEADER[1],
        _row("every field", everything),
        "",
        "## Per field",
        "",
        *field_table(normal, fields),
        "",
        "## Per defect",
        "",
        *by_defect(normal),
        "",
        *(["## Per layout", "", *by_layout(normal), ""] if len({r.get("layout") for r in normal}) > 1 else []),
        "## Wrong and ACCEPTED",
        "",
        *accepted_wrong(normal),
        "",
        f"## Cards with a number of the wrong shape ({len(bad)})",
        "",
        "Right outcome for the number: not ACCEPTED (NEEDS_REVIEW or no value). `Correct` below means exactly that; an ACCEPTED number is wrong.",
        "",
        *field_table(bad, fields),
        "",
        f"Time per card: median {statistics.median(seconds):.1f} s, slowest {max(seconds):.1f} s." if seconds else "",
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out")
    args = parser.parse_args()
    results = HERE / "results" / "dl_results.json"
    if not results.exists():
        sys.stderr.write(f"{results} is missing: run run.py first\n")
        return 2
    text = build(json.loads(results.read_text()))
    Path(args.out or HERE / "BASELINE.md").write_text(text)
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
