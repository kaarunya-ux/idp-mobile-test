"""Turns ``results/aadhaar_results.json`` into the per-field tables of ``BASELINE.md`` (the committed baseline).

    python accuracy/aadhaar/report.py [--out BASELINE.md]

Counts only: every card is invented, and no value is copied into the report.
"""

import argparse
import json
import statistics
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from card_set import FIELDS  # noqa: E402
from score import OUTCOMES  # noqa: E402


def field_table(rows: list[dict], fields: tuple[str, ...] = FIELDS) -> list[str]:
    lines = ["| Field | Cards | Correct | Wrong | Empty | Review (value right) | Correct % |", "|---|---|---|---|---|---|---|"]
    for key in fields:
        cells = [r["fields"][key] for r in rows]
        counts = Counter(c["outcome"] for c in cells)
        right = sum(bool(c.get("review_right")) for c in cells if c["outcome"] == "review")
        share = 100 * counts["correct"] / len(cells) if cells else 0
        shown = [str(counts[o]) if o != "review" else f"{counts[o]} ({right})" for o in OUTCOMES]
        lines.append(f"| {key} | {len(cells)} | " + " | ".join(shown) + f" | {share:.0f}% |")
    return lines


def by_variation(rows: list[dict]) -> list[str]:
    """Share of fields read correctly, per picture variation (a card with two effects counts under both)."""
    groups: dict[str, list[dict]] = {}
    for r in rows:
        for label in [f"font {r['font']}"] * (not r["effects"]) + list(r["effects"]):
            groups.setdefault(label, []).append(r)
    lines = ["| Variation | Cards | Fields correct |", "|---|---|---|"]
    for label, group in sorted(groups.items()):
        total = [c["outcome"] for r in group for c in r["fields"].values()]
        lines.append(f"| {label} | {len(group)} | {100 * total.count('correct') / len(total):.0f}% |")
    return lines


def build(rows: list[dict]) -> str:
    normal = [r for r in rows if r["group"] == "normal"]
    bad = [r for r in rows if r["group"] == "wrong_checksum"]
    seconds = [r["seconds"] for r in rows if r["seconds"]]
    out = [
        "# Aadhaar accuracy baseline (extraction `POST /api/v1/extract`)",
        "",
        f"{len(rows)} invented cards: {len(normal)} with a valid number (scored for accuracy) and {len(bad)} whose number has a wrong "
        "check digit (own class). Generated by `report.py` from `run.py`; the committed numbers are the baseline. Counts only.",
        "",
        "How a field is scored: `correct` the printed value; `wrong` a different value; `empty` no value (or the document was not "
        "recognised as an Aadhaar card); `review` sent to a person (NEEDS_REVIEW), with the number of those whose value was right in "
        "brackets. The Aadhaar number comes back masked and counts as correct only as exactly `XXXX XXXX` plus the printed last four "
        "digits.",
        "",
        f"## Cards with a valid number ({len(normal)})",
        "",
        *field_table(normal),
        "",
        "### By picture variation",
        "",
        *by_variation(normal),
        "",
        f"## Cards with a wrong check digit ({len(bad)})",
        "",
        "Right outcome for the Aadhaar number: NEEDS_REVIEW (or no value) and still masked. `correct` below means exactly that; "
        "an ACCEPTED number or an unmasked one is `wrong`.",
        "",
        *field_table(bad),
        "",
        f"Time per card: median {statistics.median(seconds):.1f} s, slowest {max(seconds):.1f} s." if seconds else "",
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(HERE / "BASELINE.md"))
    args = parser.parse_args()
    results = HERE / "results" / "aadhaar_results.json"
    if not results.exists():
        sys.stderr.write(f"{results} is missing: run run.py first\n")
        return 2
    text = build(json.loads(results.read_text()))
    Path(args.out).write_text(text)
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
